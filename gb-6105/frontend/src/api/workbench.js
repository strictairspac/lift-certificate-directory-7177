import { request } from "./http.js";

export const api = {
  config: () => request("/workbench"),
  login: data => request("/auth/login", {method: "POST", data}),
  cases: () => request("/cases"),
  createCase: data => request("/cases", {method: "POST", data}),
  runs: () => request("/runs"),
  run: (id, signal) => request(`/runs/${id}`, {signal}),
  enqueue: (id, data) => request(`/cases/${id}/runs`, {method: "POST", data}),
  review: id => request(`/runs/${id}/review`),
  submitReview: (id, data) => request(`/runs/${id}/review`, {method: "POST", data}),
  export: id => request(`/runs/${id}/export`, {raw: true}),
  audit: () => request("/audit", {signal: AbortSignal.timeout(5000)}),
  directoryOverview: signal => request("/directory/overview", {signal}),
  directoryVersions: () => request("/directory/versions"),
  directoryCertificates: () => request("/directory/certificates"),
  directoryChanges: () => request("/directory/changes"),
  registerCertificate: data => request("/directory/certificates", {method: "POST", data}),
  revokeCertificate: data => request("/directory/revoke", {method: "POST", data}),
  requestRebuild: data => request("/directory/rebuild", {method: "POST", data}),
  createProbeBatch: data => request("/directory/probes", {method: "POST", data}),
  probeBatches: () => request("/directory/probes"),
  probeBatch: id => request(`/directory/probes/${id}`),
  exportProbeBatch: id => request(`/directory/probes/${id}/export`, {raw: true}),
};
